export type TranslationKey = keyof typeof STRINGS.en;
export const PANEL_KEYS = [
	"agent",
	"activity",
	"alerts",
	"todos",
	"context",
	"prefill",
	"workspace",
	"usage",
	"subagents",
	"tools",
] as const;
export type PanelKey = (typeof PANEL_KEYS)[number];
export function panelIdForTitle(title: string): PanelKey | undefined {
	return PANEL_KEYS.find((key) => STRINGS.en[key] === title || STRINGS.it[key] === title);
}

type LocaleEnvironment = Partial<Pick<NodeJS.ProcessEnv, "LC_ALL" | "LC_MESSAGES" | "LANG">>;

export function resolveLanguage(
	setting: LanguageSetting,
	environment: LocaleEnvironment = process.env,
): Language {
	if (setting !== "auto") return setting;
	for (const locale of [environment.LC_ALL, environment.LC_MESSAGES, environment.LANG]) {
		if (!locale?.trim()) continue;
		const prefix = /^([a-z]{2})(?:[_\-.@]|$)/i.exec(locale.trim())?.[1]?.toLowerCase();
		if (prefix === "it" || prefix === "en") return prefix;
		return "en";
	}
	return "en";
}

export function t(language: LanguageSetting, key: TranslationKey): string {
	const resolved = resolveLanguage(language);
	return STRINGS[resolved][key];
}
